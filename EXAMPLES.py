# EXAMPLE 6: CUSTOM PREPROCESSING
# ============================================================================

def demonstrate_custom_preprocessing(
    filepath="amazon_electronics_reviews.csv",
):
    """
    Load a CSV and apply custom preprocessing.

    This example demonstrates how domain-specific stopwords can be
    added before producing the two model representations.

    Be careful when adding domain-specific stopwords. Removing words
    such as 'battery', 'screen', or 'phone' could remove information
    that is central to the research question.
    """
    print("=" * 80)
    print("EXAMPLE 6: CUSTOM PREPROCESSING")
    print("=" * 80)

    from data_loader import AmazonReviewsDataLoader

    df = AmazonReviewsDataLoader.load_from_csv(filepath)

    preprocessor = TextPreprocessor()

    # Add only words that are genuinely uninformative for the analysis.
    preprocessor.stop_words.update([
        "device",
        "year",
        "month",
        "day",
    ])

    processed = preprocessor.process_reviews_df(df)

    print("\nSample custom preprocessing:")
    print("Original:")
    print(processed["text"].iloc[0])

    print("\nLDA tokens:")
    print(processed["tokens"].iloc[0])

    print("\nBERTopic text:")
    print(processed["text_cleaned"].iloc[0])

    return processed


