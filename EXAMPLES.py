# ============================================================================
# EXAMPLE 2: ANALYZE REAL AMAZON ELECTRONICS REVIEWS
# ============================================================================

def run_real_dataset(
    filepath="amazon_electronics_reviews.csv",
    output_dir="results_electronics",
    nrows=None,
    sample_per_rating=None,
    optimize_topics=True,
):
    """
    Run the complete analysis on a real Amazon reviews CSV.

    Args:
        filepath: Path to the Amazon reviews CSV.
        output_dir: Directory for generated results.
        nrows: Optional maximum number of source rows to load.
        sample_per_rating: Optional maximum number of reviews to retain
            for each star rating.
        optimize_topics: If True, compare both models across the same
            candidate topic counts before selecting final topic counts.

    The CSV must contain review text and star-rating columns. The loader
    recognizes common names such as review_body and star_rating.

    Ensure the CSV is already restricted to electronics reviews if the
    research question is specifically about that product category.
    """
    print("=" * 80)
    print("EXAMPLE 2: REAL AMAZON REVIEWS")
    print("=" * 80)

    pipeline = AspectSentimentPipeline(output_dir=output_dir)

    pipeline.run_full_pipeline(
        filepath=filepath,
        use_demo=False,
        num_topics=10,
        nrows=nrows,
        sample_per_rating=sample_per_rating,
        optimize_lda=optimize_topics,
    )

    print("\nReal-data analysis finished.")
    print(f"Results directory: {output_dir}/")

    return pipeline


# ============================================================================
# EXAMPLE 3: INSPECT THE GENERATED RESULTS
# ============================================================================

def inspect_results(results_dir="results_electronics"):
    """
    Load and inspect CSV outputs generated by the pipeline.

    This function does not retrain either model.
    """
    results_path = Path(results_dir)

    if not results_path.is_dir():
        raise FileNotFoundError(
            f"Results directory does not exist: {results_path}"
        )

    print("=" * 80)
    print("EXAMPLE 3: INSPECT PIPELINE RESULTS")
    print("=" * 80)

    files_to_inspect = {
        "LDA aspect sentiment": "lda_aspect_sentiment.csv",
        "BERTopic aspect sentiment": "bertopic_aspect_sentiment.csv",
        "LDA negative drivers": "lda_negative_drivers.csv",
        "BERTopic negative drivers": "bertopic_negative_drivers.csv",
        "LDA one-star aspect percentages":
            "lda_one_star_aspect_percentages.csv",
        "BERTopic one-star aspect percentages":
            "bertopic_one_star_aspect_percentages.csv",
    }

    loaded_results = {}

    for description, filename in files_to_inspect.items():
        filepath = results_path / filename

        if not filepath.is_file():
            print(f"\nSkipping unavailable file: {filename}")
            continue

        df = pd.read_csv(filepath)
        loaded_results[description] = df

        print("\n" + "-" * 80)
        print(description.upper())
        print("-" * 80)
        print(df.head(10).to_string(index=False))

    return loaded_results


# ============================================================================
# EXAMPLE 4: EXAMINE ONE-STAR REVIEW DRIVERS
# ============================================================================

def inspect_one_star_aspects(results_dir="results_electronics"):
    """
    Examine the percentage of all one-star reviews associated with
    each discovered topic.

    The generated percentages are based on topic association, not
    necessarily a manually verified semantic aspect label.

    For LDA, a review may be associated with multiple topics, so
    percentages can sum to more than 100 percent.
    """
    results_path = Path(results_dir)

    print("=" * 80)
    print("EXAMPLE 4: ONE-STAR REVIEW ASPECT ANALYSIS")
    print("=" * 80)

    for model_name, filename in [
        ("LDA", "lda_one_star_aspect_percentages.csv"),
        ("BERTopic", "bertopic_one_star_aspect_percentages.csv"),
    ]:
        filepath = results_path / filename

        print(f"\n{model_name}")
        print("-" * 40)

        if not filepath.is_file():
            print(f"Result file not found: {filepath}")
            continue

        df = pd.read_csv(filepath)

        if df.empty:
            print("No one-star aspect results are available.")
            continue

        print(df.to_string(index=False))

    print(
        "\nInterpretation reminder: a topic's percentage describes "
        "its association with the one-star review set. It does not "
        "prove that the topic caused the low rating."
    )


