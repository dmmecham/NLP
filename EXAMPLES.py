# EXAMPLE 5: EXAMINE THE TWO PREPROCESSING STREAMS
# ============================================================================

def demonstrate_preprocessing():
    """
    Show how the same reviews are represented differently for LDA
    and BERTopic.
    """
    print("=" * 80)
    print("EXAMPLE 5: SEPARATE PREPROCESSING STREAMS")
    print("=" * 80)

    reviews = pd.DataFrame({
        "text": [
            "The battery lasts all day!",
            "The battery does NOT last long.",
            "I love this screen. The colors look amazing!",
            "The display is not bright enough.",
        ],
        "rating": [5, 1, 5, 2],
    })

    preprocessor = TextPreprocessor()

    processed = preprocessor.process_reviews_df(reviews)

    for index, row in processed.iterrows():
        print(f"\nReview {index + 1}")
        print(f"Original:  {row['text']}")
        print(f"LDA:       {row['tokens']}")
        print(f"BERTopic:  {row['text_cleaned']}")

    return processed


